const dicts: Record<LangCode, Dict> = { en, hi, bn, ta, te, mr, gu, as: as_, kn };

type Ctx = {
  lang: LangCode;
  setLang: (l: LangCode) => void;
  t: (key: string, vars?: Record<string, string>) => string;
  speechLang: string;
};

const LangContext = createContext<Ctx | null>(null);

const KEY = "icses-lang";

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<LangCode>("en");

  useEffect(() => {
    try {
      const saved = sessionStorage.getItem(KEY) as LangCode | null;
      if (saved && dicts[saved]) setLangState(saved);
    } catch {
      /* ignore */
    }
  }, []);

  const value = useMemo<Ctx>(() => {
    const dict = dicts[lang];
    return {
      lang,
      setLang: (l) => {
        setLangState(l);
        try {
          sessionStorage.setItem(KEY, l);
        } catch {
          /* ignore */
        }
      },
      t: (key, vars) => {
        let out = dict[key] ?? en[key] ?? key;
        if (vars)
          for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, v);
        return out;
      },
      speechLang: languages.find((l) => l.code === lang)?.speech ?? "en-IN",
    };
  }, [lang]);

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useLang must be used inside LanguageProvider");
  return ctx;
}
